DECLARE
    existing_order RECORD;
BEGIN
    FOR existing_order IN SELECT order_json, status FROM public.orders LOOP
        PERFORM public.adjust_product_order_totals(existing_order.order_json, existing_order.status, 1);
    END LOOP;
END;
$$;
