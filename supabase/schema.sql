CREATE OR REPLACE FUNCTION public.admin_login_email(p_username TEXT)
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT email
    FROM public.admin_user
    WHERE lower(username) = lower(btrim(p_username))
      AND username IS NOT NULL
    LIMIT 1
$$;

REVOKE ALL ON FUNCTION public.admin_login_email(TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_login_email(TEXT) TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.admin_is_authorized()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.admin_user
        WHERE auth_user_id = auth.uid()
    )
$$;

REVOKE ALL ON FUNCTION public.admin_is_authorized() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_is_authorized() TO authenticated;

CREATE OR REPLACE FUNCTION public.create_customer_profile()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    phone_value TEXT;
    phone_digits TEXT;
BEGIN
    phone_value := coalesce(
        nullif(btrim(NEW.raw_user_meta_data ->> 'phone'), ''),
        NEW.phone,
        ''
    );
    phone_digits := right(regexp_replace(phone_value, '[^0-9]', '', 'g'), 10);
    IF length(phone_digits) = 10 THEN
        INSERT INTO public.customers (id, name, phone)
        VALUES (
            NEW.id,
            coalesce(nullif(btrim(NEW.raw_user_meta_data ->> 'name'), ''), ''),
            phone_digits
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS create_customer_profile_after_signup ON auth.users;
CREATE TRIGGER create_customer_profile_after_signup
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.create_customer_profile();

INSERT INTO public.customers (id, name, phone)
SELECT
    users.id,
    coalesce(nullif(btrim(users.raw_user_meta_data ->> 'name'), ''), ''),
    right(regexp_replace(coalesce(
        nullif(btrim(users.raw_user_meta_data ->> 'phone'), ''),
        users.phone,
        ''
    ), '[^0-9]', '', 'g'), 10)
FROM auth.users AS users
WHERE length(right(regexp_replace(coalesce(
    nullif(btrim(users.raw_user_meta_data ->> 'phone'), ''),
    users.phone,
    ''
), '[^0-9]', '', 'g'), 10)) = 10
ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.track_order_by_id_and_phone(
    p_order_id TEXT,
    p_phone TEXT
)
RETURNS TABLE (
    id TEXT,
    order_json TEXT,
    status TEXT,
    created_at TEXT,
    customer_phone TEXT,
    customer_name TEXT,
    total_amount NUMERIC
)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
    WITH supplied_phone AS (
        SELECT right(regexp_replace(coalesce(p_phone, ''), '[^0-9]', '', 'g'), 10) AS digits
    )
    SELECT orders.id,
           orders.order_json,
           orders.status,
           orders.created_at,
           orders.customer_phone,
           orders.customer_name,
           orders.total_amount
    FROM public.orders AS orders
    CROSS JOIN supplied_phone
    WHERE upper(orders.id) = upper(btrim(p_order_id))
      AND length(supplied_phone.digits) = 10
      AND length(regexp_replace(coalesce(orders.customer_phone, ''), '[^0-9]', '', 'g')) >= 10
      AND right(regexp_replace(coalesce(orders.customer_phone, ''), '[^0-9]', '', 'g'), 10) = supplied_phone.digits
$$;

REVOKE ALL ON FUNCTION public.track_order_by_id_and_phone(TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.track_order_by_id_and_phone(TEXT, TEXT) TO anon, authenticated;

