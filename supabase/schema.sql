CREATE OR REPLACE FUNCTION public.adjust_product_order_totals(
    p_order_json TEXT,
    p_status TEXT,
    p_delta INTEGER
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    grouped_product RECORD;
BEGIN
    IF lower(coalesce(p_status, '')) IN ('cancelled', 'canceled') THEN
        RETURN;
    END IF;

    FOR grouped_product IN
        SELECT
            coalesce(nullif(item->>'code', ''), nullif(item->>'nameEn', '')) AS product_code,
            SUM(
                CASE
                    WHEN (item->>'qty') ~ '^[0-9]{1,6}$'
                        THEN greatest((item->>'qty')::BIGINT, 1)
                    ELSE 1
                END
            )::BIGINT AS units_sold
        FROM jsonb_array_elements(
            CASE
                WHEN jsonb_typeof((p_order_json::JSONB)->'items') = 'array'
                    THEN (p_order_json::JSONB)->'items'
                ELSE '[]'::JSONB
            END
        ) AS order_items(item)
        WHERE coalesce(nullif(item->>'code', ''), nullif(item->>'nameEn', '')) IS NOT NULL
        GROUP BY 1
    LOOP
        IF p_delta > 0 THEN
            INSERT INTO public.product_order_totals AS totals (product_code, order_count, units_sold)
            VALUES (grouped_product.product_code, p_delta, grouped_product.units_sold * p_delta)
            ON CONFLICT (product_code) DO UPDATE
            SET order_count = totals.order_count + EXCLUDED.order_count,
                units_sold = totals.units_sold + EXCLUDED.units_sold;
        ELSE
            UPDATE public.product_order_totals
            SET order_count = order_count + p_delta,
                units_sold = units_sold + (grouped_product.units_sold * p_delta)
            WHERE product_code = grouped_product.product_code;

            DELETE FROM public.product_order_totals
            WHERE product_code = grouped_product.product_code AND order_count <= 0;
        END IF;
    END LOOP;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_product_order_totals()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM public.adjust_product_order_totals(OLD.order_json, OLD.status, -1);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM public.adjust_product_order_totals(NEW.order_json, NEW.status, 1);
    END IF;

    RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.adjust_product_order_totals(TEXT, TEXT, INTEGER) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.sync_product_order_totals() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS sync_product_order_totals_after_change ON public.orders;
CREATE TRIGGER sync_product_order_totals_after_change
    AFTER INSERT OR UPDATE OR DELETE ON public.orders
    FOR EACH ROW EXECUTE FUNCTION public.sync_product_order_totals();

