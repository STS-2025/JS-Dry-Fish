CREATE TABLE IF NOT EXISTS public.product_rating_totals (
    product_code TEXT PRIMARY KEY REFERENCES public.products(code) ON DELETE CASCADE,
    rating_sum INTEGER NOT NULL CHECK (rating_sum >= 0),
    reviews INTEGER NOT NULL CHECK (reviews >= 0)
);

ALTER TABLE public.product_rating_totals ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read product rating totals" ON public.product_rating_totals;
CREATE POLICY "Allow public read product rating totals" ON public.product_rating_totals
    FOR SELECT TO anon, authenticated USING (true);

REVOKE ALL ON TABLE public.product_rating_totals FROM anon, authenticated;
GRANT SELECT ON TABLE public.product_rating_totals TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.sync_product_rating_totals()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.product_rating_totals AS totals (product_code, rating_sum, reviews)
        VALUES (NEW.product_code, NEW.rating, 1)
        ON CONFLICT (product_code) DO UPDATE
        SET rating_sum = totals.rating_sum + EXCLUDED.rating_sum,
            reviews = totals.reviews + EXCLUDED.reviews;
    ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.product_code = NEW.product_code THEN
            UPDATE public.product_rating_totals
            SET rating_sum = rating_sum + NEW.rating - OLD.rating
            WHERE product_code = NEW.product_code;
        ELSE
            UPDATE public.product_rating_totals
            SET rating_sum = rating_sum - OLD.rating,
                reviews = reviews - 1
            WHERE product_code = OLD.product_code;

            DELETE FROM public.product_rating_totals
            WHERE product_code = OLD.product_code AND reviews = 0;

            INSERT INTO public.product_rating_totals AS totals (product_code, rating_sum, reviews)
            VALUES (NEW.product_code, NEW.rating, 1)
            ON CONFLICT (product_code) DO UPDATE
            SET rating_sum = totals.rating_sum + EXCLUDED.rating_sum,
                reviews = totals.reviews + EXCLUDED.reviews;
        END IF;
    ELSIF TG_OP = 'DELETE' THEN
        UPDATE public.product_rating_totals
        SET rating_sum = rating_sum - OLD.rating,
            reviews = reviews - 1
        WHERE product_code = OLD.product_code;

        DELETE FROM public.product_rating_totals
        WHERE product_code = OLD.product_code AND reviews = 0;
    END IF;

    RETURN NULL;
END;
$$;

REVOKE ALL ON FUNCTION public.sync_product_rating_totals() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS sync_product_rating_totals_after_change ON public.product_ratings;
CREATE TRIGGER sync_product_rating_totals_after_change
    AFTER INSERT OR UPDATE OR DELETE ON public.product_ratings
    FOR EACH ROW EXECUTE FUNCTION public.sync_product_rating_totals();

INSERT INTO public.product_rating_totals (product_code, rating_sum, reviews)
SELECT product_code, SUM(rating)::INTEGER, COUNT(*)::INTEGER
FROM public.product_ratings
GROUP BY product_code
ON CONFLICT (product_code) DO UPDATE
SET rating_sum = EXCLUDED.rating_sum,
    reviews = EXCLUDED.reviews;

DELETE FROM public.product_rating_totals totals
WHERE NOT EXISTS (
    SELECT 1
    FROM public.product_ratings ratings
    WHERE ratings.product_code = totals.product_code
);

DROP VIEW IF EXISTS public.product_rating_summaries;
CREATE OR REPLACE VIEW public.product_rating_summaries
WITH (security_invoker = true) AS
SELECT
    product_code,
    ROUND(rating_sum::NUMERIC / NULLIF(reviews, 0), 1) AS rating,
    reviews
FROM public.product_rating_totals
WHERE reviews > 0;

GRANT SELECT ON public.product_rating_summaries TO anon, authenticated;

